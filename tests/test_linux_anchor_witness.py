"""Opt-in native root witness tests; no mock witness or Core E2E claim."""
import os
from pathlib import Path
import platform
import secrets
import selectors
import subprocess
import sys
import unittest
from wam_regtest.linux_anchor_witness import LinuxRootWitnessAnchor,LinuxWitnessError


@unittest.skipUnless(sys.platform=='linux' and platform.machine()=='x86_64'
    and os.environ.get('WAM_ROOT_WITNESS_NATIVE_TESTS')=='1','explicit native ephemeral root-witness acceptance only')
class NativeRootWitness(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if os.geteuid()==0:raise RuntimeError('Tests require ordinary wallet user plus separate root witness')
        subprocess.run(['sudo','-n','true'],check=True,timeout=10)
        cls.service=Path('/usr/local/libexec')/('wam-regtest-witness-'+secrets.token_hex(8)+'.py')
        cls.root=Path('/tmp')/('wam-root-witness-'+secrets.token_hex(8))
        cls.process=None
        subprocess.run(['sudo','-n','install','-d','-m755','/usr/local/libexec'],check=True)
        source=Path(__file__).resolve().parents[1]/'src/wam_regtest/linux_anchor_witness.py'
        subprocess.run(['sudo','-n','install','-o','root','-g','root','-m755',str(source),str(cls.service)],check=True)
        try:cls.start(provision=True)
        except Exception:cls.tearDownClass();raise
    @classmethod
    def start(cls,provision=False):
        cls.process=subprocess.Popen(['sudo','-n','/usr/bin/python3','-I',str(cls.service),
            '--state-root',str(cls.root),'--uid',str(os.geteuid()),*(['--provision'] if provision else [])],
            stdin=subprocess.DEVNULL,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
        selector=selectors.DefaultSelector();selector.register(cls.process.stdout,selectors.EVENT_READ)
        try:
            if not selector.select(15):raise RuntimeError('Native witness readiness timeout')
            line=cls.process.stdout.readline().strip()
            if not line.startswith('ROOT_WITNESS_READY '):raise RuntimeError('Native root witness startup denied')
            cls.server_pid=int(line.split()[1])
        finally:selector.close()
    @classmethod
    def stop(cls):
        if cls.process is None:return
        if cls.process.poll() is None:
            subprocess.run(['sudo','-n','kill','-KILL',str(cls.server_pid)],check=True,timeout=10)
        cls.process.wait(timeout=15);cls.process.stdout.close();cls.process.stderr.close();cls.process=None
    @classmethod
    def tearDownClass(cls):
        try:cls.stop()
        finally:
            # Exact disposable root/service paths generated by this class only.
            subprocess.run(['sudo','-n','rm','-rf','--',str(cls.root)],check=True,timeout=15)
            subprocess.run(['sudo','-n','rm','-f','--',str(cls.service)],check=True,timeout=15)
    def anchor(self,wallet_id=None):return LinuxRootWitnessAnchor(wallet_id or secrets.token_hex(16),self.root/'anchor.sock')
    def test_root_peer_monotonic_cas_and_stale_writer_rejection(self):
        anchor=self.anchor();self.assertIsNone(anchor.read())
        one=(1,'a'*64);two=(2,'b'*64)
        anchor.advance(None,one);anchor.advance(one,two);self.assertEqual(anchor.read(),two)
        with self.assertRaises(LinuxWitnessError):anchor.advance(one,(2,'c'*64))
        with self.assertRaises(LinuxWitnessError):anchor.advance(two,one)
        self.assertEqual(anchor.read(),two)
        self.assertFalse(os.access(self.root/'records',os.R_OK))
    def test_same_wallet_contention_and_exact_object_reentry(self):
        anchor=self.anchor()
        with anchor.lease(),anchor.lease():
            self.assertIsNone(anchor.read())
            with self.assertRaises(LinuxWitnessError):self.anchor(anchor.wallet_id).read()
        self.assertIsNone(self.anchor(anchor.wallet_id).read())
    def test_crash_restart_retains_anchor_and_detects_lost_lease(self):
        anchor=self.anchor();record=(1,'d'*64);anchor.advance(None,record)
        with self.assertRaises(LinuxWitnessError):
            with anchor.lease():
                self.stop()
        self.start()
        self.assertEqual(anchor.read(),record)
    def test_missing_unprivileged_endpoint_and_uninstalled_service_deny(self):
        with self.assertRaises((LinuxWitnessError,OSError)):
            LinuxRootWitnessAnchor('a'*32,Path('/tmp/nonexistent-wam-witness/anchor.sock')).read()
        source=Path(__file__).resolve().parents[1]/'src/wam_regtest/linux_anchor_witness.py'
        result=subprocess.run(['sudo','-n','/usr/bin/python3','-I',str(source),
            '--state-root',str(self.root),'--uid',str(os.geteuid())],capture_output=True,timeout=10)
        self.assertEqual(result.returncode,2)
        self.assertIn(b'ROOT_WITNESS_START_DENIED',result.stderr)


